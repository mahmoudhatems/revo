export const GLYPHS = Object.keys(G);

const SIZE_PX = { sm: 20, md: 30, lg: 40, xl: 60, xxl: 80 } as const;
export type IconSize = keyof typeof SIZE_PX;

// Card icons that map onto drawn glyphs
const ALIAS: Record<string, string> = {
  panel1: "panel",
  panel2: "panel",
  panel3: "panel",
  panel4: "panel",
  thermometer: "thermo",
  star: "starG",
};

export function Icon({
  name,
  size = "md",
  className = "",
  title,
}: {
  name: string;
  size?: IconSize | number;
  className?: string;
  title?: string;
}) {
  const px = typeof size === "number" ? size : SIZE_PX[size];
  const img = IMAGE_ICONS[name];
  if (img && !G[name]) {
    return (
      <img
        src={img}
        alt={title ?? ""}
        aria-hidden={title ? undefined : true}
        width={px}
        height={px}
        className={`pixelated inline-block object-contain shrink-0 ${className}`}
        draggable={false}
      />
    );
  }
  const key = ALIAS[name] ?? name;
  const map = G[key];
  if (!map)
    return (
      <span className={`inline-block shrink-0 ${className}`} style={{ width: px, height: px }} />
    );
  const rects: React.ReactNode[] = [];
  map.forEach((row, y) =>
    row.split("").forEach((ch, x) => {
      if (ch !== "." && P[ch])
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={P[ch]} />);
    }),
  );
  return (
    <svg
      viewBox="0 0 10 10"
      width={px}
      height={px}
      className={`inline-block shrink-0 ${className}`}
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
    >
      {title ? <title>{title}</title> : null}
      {rects}
    </svg>
  );
}

/** Panel count badge for Mission 1 cards. */
export function PanelCount({ n, size = 36 }: { n: number; size?: number }) {
  return (
    <span className="inline-flex gap-1">
      {Array.from({ length: n }).map((_, i) => (
        <Icon key={i} name="panel" size={size} />
      ))}
    </span>
  );
}
